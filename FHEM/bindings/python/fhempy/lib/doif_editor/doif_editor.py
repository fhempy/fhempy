    async def save_rule(self, data):
        """data: {name, new, type, model or def, attrs, room, alias}"""
        name = str(data.get("name") or "").strip()
        rule_type = data.get("type") or "DOIF"
        new = bool(data.get("new"))
        existing = await self.fetch_rules([name]) if name else {}
        if new:
            name = await self.unique_name(
                name or "di_" + values.reading_name(data.get("title") or "Regel")
            )
        elif name not in existing:
            return f"{name} not found"
        if data.get("model") is not None:
            model = data["model"]
            definition = parser.generate_definition(model)
            attrs = parser.generate_attrs(model)
        else:
            definition = str(data.get("def") or "")
            attrs = dict(data.get("attrs") or {})
        definition = definition.strip("\n") if new else definition
        for key in ("room", "alias", "comment"):
            if data.get(key) not in (None, ""):
                attrs[key] = data[key]
        old = existing.get(name)
        if old is not None:
            self.add_version(
                name, old["TYPE"], old.get("DEF", ""), self._doif_attrs(old), "before"
            )
        managed = set(DOIF_ATTRS) - {"disable"} if rule_type == "DOIF" else set()
        error = await self.apply_rule(name, rule_type, definition, attrs, managed)
        if error:
            if error == "type":
                return f"{name} is no {rule_type}"
            return error
        stored = {
            k: v for k, v in attrs.items() if v not in (None, "") and k in DOIF_ATTRS
        }
        self.add_version(
            name, rule_type, definition, stored, data.get("note", "editor")
        )
        self.add_change(name, "created" if new else "saved", data.get("summary", ""))
        await self.save_data()
        return dumps({"ok": True, "name": name})

    async def unique_name(self, wanted):
        for char, repl in UMLAUTS.items():
            wanted = wanted.replace(char, repl)
        wanted = re.sub(r"[^A-Za-z0-9._]", "_", wanted)[:60] or "di_Regel"
        cmd = (
            f"my $b = {fhem.perlString(wanted)}; my $n = $b; my $i = 2;"
            " while (defined($defs{$n})) { $n = $b . '_' . $i++ } $n"
        )
        return str(await fhem.sendCommandHash(self.hash, cmd))

