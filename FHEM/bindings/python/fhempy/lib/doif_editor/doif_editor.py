    async def find_history(self):
        cmd = (
            "join(',', grep { ($defs{$_}{FHEMPYTYPE} // '') eq 'timeline' }"
            " sort keys %defs)"
        )
        names = [
            n for n in str(await fhem.sendCommandHash(self.hash, cmd)).split(",") if n
        ]
        old = self._history
        self._history = None
        for name in names:
            path = os.path.join(os.getcwd(), ".fhempy", "timeline", f"{name}.db")
            history = History(path)
            if history.available():
                self._history = history
                break
        if old is not None and (
            self._history is None or old.path != self._history.path
        ):
            await utils.run_blocking(functools.partial(old.close))

    async def blocking(self, function, *args, **kwargs):
        return await utils.run_blocking(functools.partial(function, *args, **kwargs))

    # --- events -------------------------------------------------------------

    async def register_events(self):
        await self.unregister_events()
        devices = set()
        for value in self.data["values"]:
            devices |= {device for device, _ in values.sources_of(value)}
            for row in value.get("rows", []):
                if row.get("only_if"):
                    devices |= {d for d, _ in self.pairs_of_tree(row["only_if"])}
        devices.discard("")
        devices.discard(self.hash["NAME"])
        names = sorted(devices) + ["global"]
        for name in names:
            fhem.register_event_listener(name, self.handle_event)
        self._listening = names
        await fhem.setEventDevices(self.hash, names)

    async def unregister_events(self):
        for name in self._listening:
            fhem.unregister_event_listener(name, self.handle_event)
        if self._listening and self._stopping:
            await fhem.setEventDevices(self.hash, [])
        self._listening = []

    async def handle_event(self, device, reading, value):
        if device == "global":
            self.handle_global(value)
            return
        self.schedule_values()

    def handle_global(self, value):
        words = str(value).split(" ")
        if len(words) < 2:
            return
        if words[0] in ("DEFINED", "MODIFIED", "DELETED", "RENAMED"):
            self._index_time = 0
            if not words[1].endswith(TEMP_SUFFIX):
                self._global_pending.add((words[0], words[1], " ".join(words[2:])))
                self.schedule_global()
        elif words[0] in ("ATTR", "DELETEATTR") and len(words) > 2:
            self._index_time = 0
            if words[2] in DOIF_ATTRS:
                self._global_pending.add(("ATTR", words[1], ""))
                self.schedule_global()

    def schedule_global(self):
        if self._global_task is not None and not self._global_task.done():
            return

        async def later():
            await asyncio.sleep(GLOBAL_DELAY)
            pending, self._global_pending = self._global_pending, set()
            await self.record_global(pending)

        self._global_task = self.create_async_task(later())

    async def record_global(self, pending):
        """change history and versions also for changes outside the editor"""
        changed = False
        names = sorted({name for _, name, _ in pending})
        infos = await self.fetch_rules(names)
        for action, name, extra in sorted(pending):
            if name in self._own_changes:
                continue
            info = infos.get(name)
            if action == "DELETED":
                self.add_change(name, "deleted")
                changed = True
            elif action == "RENAMED":
                self.add_change(name, "renamed", extra)
                changed = True
            elif info is not None and info.get("TYPE") in index.RULE_TYPES:
                attrs = {
                    k: v for k, v in info.get("attrs", {}).items() if k in DOIF_ATTRS
                }
                if self.add_version(
                    name, info["TYPE"], info.get("DEF", ""), attrs, "FHEM"
                ):
                    self.add_change(
                        name, "defined" if action == "DEFINED" else "modified"
                    )
                    changed = True
        self._own_changes.clear()
        if changed:
            await self.save_data()

    # --- reading FHEM -------------------------------------------------------

    async def fetch_rules(self, names=None):
        """DEF, attributes, readings of the DOIF/notify/at/watchdog devices"""
        types = ",".join(fhem.perlString(t) for t in index.RULE_TYPES)
        selection = (
            "(" + ",".join(fhem.perlString(n) for n in names) + ")"
            if names is not None
            else "(sort keys %defs)"
        )
        if names is not None and not names:
            return {}
        cmd = (
            "my %t = map { $_ => 1 } (" + types + "); my %r;"
            " foreach my $d " + selection + " { my $h = $defs{$d};"
            " next if (!$h || !$t{$h->{TYPE}} || $h->{TEMPORARY});"
            " my (%rd, %ts); foreach my $k (keys %{$h->{READINGS}}) {"
            " $rd{$k} = substr($h->{READINGS}{$k}{VAL} // '', 0, 300);"
            " $ts{$k} = $h->{READINGS}{$k}{TIME} }"
            " $r{$d} = {NAME => $d, TYPE => $h->{TYPE}, DEF => ($h->{DEF} // ''),"
            " attrs => ($attr{$d} // {}), readings => \\%rd, times => \\%ts,"
            " internals => { TRIGGERTIME => ($h->{TRIGGERTIME} // ''),"
            " STATE => ($h->{STATE} // '') } } }"
            " to_json(\\%r)"
        )
        return self._json(await fhem.sendCommandHash(self.hash, cmd), {})

    async def fetch_devices(self, with_sets=False, names=None):
        selection = (
            "(" + ",".join(fhem.perlString(n) for n in names) + ")"
            if names is not None
            else "(sort keys %defs)"
        )
        sets = "sets => (getAllSets($d) // '')," if with_sets else ""
        cmd = (
            "my %r; foreach my $d " + selection + " { my $h = $defs{$d};"
            " next if (!$h || $h->{TEMPORARY} || defined($h->{SNIPPET}));"
            " my %rd; foreach my $k (keys %{$h->{READINGS}}) {"
            " next if ($k =~ /^\\./);"
            " $rd{$k} = substr($h->{READINGS}{$k}{VAL} // '', 0, 80) }"
            " $r{$d} = {NAME => $d, TYPE => $h->{TYPE}, "
            + sets
            + " FHEMPYTYPE => ($h->{FHEMPYTYPE} // ''), STATE => ($h->{STATE} // ''),"
            " readings => \\%rd, attrs => { map { $_ => AttrVal($d, $_, '') }"
            " ('alias', 'room', 'group', 'genericDeviceType', 'icon', 'webCmd',"
            " 'devStateIcon', 'cmdIcon') } } }"
            " to_json(\\%r)"
        )
        return self._json(await fhem.sendCommandHash(self.hash, cmd), {})

    async def fetch_values(self, pairs):
        """current values {(device, reading): (ts, value)}"""
        pairs = sorted({p for p in pairs if p[0] and not p[0].startswith("@")})
        if not pairs:
            return {}
        items = ",".join(
            "[" + fhem.perlString(d) + "," + fhem.perlString(r or "state") + "]"
            for d, r in pairs
        )
        cmd = (
            "my @r; foreach my $p (" + items + ") { my ($d, $n) = @$p;"
            " my $h = $defs{$d}; next if (!$h);"
            " my $v = $n eq 'STATE' ? $h->{STATE} : ReadingsVal($d, $n, undef);"
            " $v = $h->{$n} if (!defined($v) && defined($h->{$n}) && !ref($h->{$n}));"
            " next if (!defined($v));"
            ' push(@r, [$d, $n, "$v", time_str2num(ReadingsTimestamp($d, $n,'
            " '1970-01-01 01:00:00'))]) } to_json(\\@r)"
        )
        rows = self._json(await fhem.sendCommandHash(self.hash, cmd), [])
        return {(row[0], row[1]): (row[3], row[2]) for row in rows if len(row) == 4}

    def _json(self, text, default):
        try:
            return json.loads(text)
        except (TypeError, ValueError):
            self.logger.error(f"Unexpected answer of FHEM: {str(text)[:300]}")
            return default

    async def get_index(self, force=False):
        async with self._index_lock:
            if (
                force
                or self._index is None
                or time.time() - self._index_time > INDEX_MAX_AGE
            ):
                rules = await self.fetch_rules()
                devices = await self.fetch_devices()
                self._index = index.Index(
                    list(rules.values()),
                    list(devices.values()),
                    editor=self.hash["NAME"],
                    values=self.data["values"],
                )
                self._index_time = time.time()
            return self._index

    async def location(self):
        latitude = await self.global_attr("latitude", "50.112")
        longitude = await self.global_attr("longitude", "8.686")
        try:
            return {"latitude": float(latitude), "longitude": float(longitude)}
        except (TypeError, ValueError):
            return {"latitude": 50.112, "longitude": 8.686}

    @staticmethod
    def pairs_of_tree(tree):
        triggers, checks, _, _ = parser.reads_and_writes(
            {"mode": "fhem", "cases": [{"cond": tree, "blocks": []}]}
        )
        return triggers | checks

    # --- computed values ----------------------------------------------------

    def schedule_values(self):
        if self._value_task is not None and not self._value_task.done():
            return

        async def later():
            await asyncio.sleep(1)
            await self.compute_values()

        self._value_task = self.create_async_task(later())

    async def value_loop(self):
        while not self._stopping:
            await asyncio.sleep(VALUE_INTERVAL)
            try:
                await self.compute_values()
            except Exception:
                self.logger.exception("Failed to compute the values")

    async def value_context(self, value_list, extra_inputs=None):
        """ctx for values.compute with all data fetched before"""
        pairs = set()
        histories = set()
        for value in value_list:
            for row in value.get("rows", []):
                source = row.get("amount", {}).get("source", {}) or {}
                if source.get("k") == "reading":
                    pairs.add((source.get("dev", ""), source.get("reading") or "state"))
                elif source.get("k") == "history":
                    histories.add(
                        (
                            source.get("dev", ""),
                            source.get("reading") or "state",
                            source.get("func", "sum"),
                            float(source.get("hours") or 24),
                        )
                    )
                if row.get("only_if"):
                    pairs |= self.pairs_of_tree(row["only_if"])
        current = await self.fetch_values(pairs)
        history_values = {}
        if histories and self._history is not None:
            for key in histories:
                try:
                    history_values[key] = await self.blocking(
                        self._history.aggregate, *key
                    )
                except Exception:
                    self.logger.debug("history not available", exc_info=True)
                    history_values[key] = None
        inputs = {
            item["name"]: item.get("value", item.get("default", ""))
            for item in self.data["inputs"]
        }
        inputs.update(extra_inputs or {})
        now = datetime.datetime.now()
        location = await self.location()
        by_name = {v.get("name"): v for v in self.data["values"]}
        results = {}
        computing = set()

        def value_of(name):
            if name in results:
                return results[name]
            if name in computing or name not in by_name:
                return None
            computing.add(name)
            results[name] = values.compute(by_name[name], ctx)[0]
            return results[name]

        def condition(tree):
            context = evaluate.Context(current, now, **location)
            context.self_name = self.hash["NAME"]
            return evaluate.eval_tree(context, tree) is True

        ctx = {
            "reading": lambda d, r: (current.get((d, r)) or (None, None))[1],
            "now": now,
            "history": lambda d, r, f, h: history_values.get((d, r, f, h)),
            "input": lambda name: inputs.get(name),
            "value": value_of,
            "condition": condition,
        }
        return ctx, results

    async def compute_values(self):
        if not self.data["values"] and not self.data["inputs"]:
            return
        ctx, results = await self.value_context(self.data["values"])
        await fhem.readingsBeginUpdate(self.hash)
        for value in self.data["values"]:
            name = value.get("name")
            if name not in results:
                results[name] = values.compute(value, ctx)[0]
            for reading, text in values.readings_of(value, results[name]).items():
                if self._results.get(reading) != text:
                    await fhem.readingsBulkUpdate(self.hash, reading, text)
                    self._results[reading] = text
        for item in self.data["inputs"]:
            text = str(item.get("value", item.get("default", "")))
            if self._results.get(item["name"]) != text:
                await fhem.readingsBulkUpdate(self.hash, item["name"], text)
                self._results[item["name"]] = text
        await fhem.readingsEndUpdate(self.hash, 1)

