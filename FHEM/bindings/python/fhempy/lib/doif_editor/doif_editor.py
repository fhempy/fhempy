    async def flaps(self, idx):
        """devices which changed often between values written by different
        rules in the last 7 days (sign of a conflict)"""
        if self._history is None:
            return {}
        devices = [d for d, names in idx.reverse_writes.items() if len(names) > 1]
        if not devices:
            return {}
        now = time.time()
        try:
            rows = await self.blocking(
                self._history.events,
                [(d, "state") for d in devices],
                now - 7 * 86400,
                now,
            )
        except Exception:
            self.logger.debug("history not readable", exc_info=True)
            return {}
        result = {}
        last = {}
        for ts, device, _, value in rows:
            previous = last.get(device)
            if previous is not None and previous[1] != value and ts - previous[0] < 120:
                result[device] = result.get(device, 0) + 1
            last[device] = (ts, value)
        return result

