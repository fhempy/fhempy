    async def with_reply(self, params, function):
        """FHEM gets an empty reply when a set takes longer than 50 ms, the
        page fetches the result with get reply <rid>"""
        try:
            data = decode(params.get("data"))
        except ValueError as exc:
            return str(exc)
        result = await function(data)
        rid = str(data.get("rid") or "")
        if rid:
            self._replies[rid] = result
            while len(self._replies) > 50:
                self._replies.pop(next(iter(self._replies)))
        return result

