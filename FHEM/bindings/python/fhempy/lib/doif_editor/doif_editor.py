    async def precedence(self, data):
        """data: {winner, loser, device}: the loser only switches the device
        while the winner is not in a case which switches it"""
        winner, loser, device = (
            data.get("winner"),
            data.get("loser"),
            data.get("device"),
        )
        infos = await self.fetch_rules([winner, loser])
        if winner not in infos or loser not in infos:
            return "rule not found"
        if infos[loser]["TYPE"] != "DOIF" or infos[winner]["TYPE"] != "DOIF":
            return "only for DOIF"
        winner_model = parser.parse_rule(
            infos[winner]["DEF"], self._doif_attrs(infos[winner])
        )
        loser_model = parser.parse_rule(
            infos[loser]["DEF"], self._doif_attrs(infos[loser])
        )
        winner_cases = index.cases_writing(winner_model, device)
        if not winner_cases:
            return f"{winner} doesn't switch {device}"
        if not index.add_precedence(loser_model, winner, winner_cases, device):
            return f"{loser} doesn't switch {device}"
        loser_model["name"] = loser
        data = {
            "name": loser,
            "type": "DOIF",
            "model": loser_model,
            "summary": f"{winner} > {loser} ({device})",
        }
        return await self.save_rule(data)

    async def set_run(self, hash, params):
        name = params.get("rule", "")
        try:
            case = int(params.get("case"))
        except (TypeError, ValueError):
            return "case must be a number"
        return str(
            await fhem.sendCommandHash(
                self.hash,
                f"CommandSet(undef, {fhem.perlString(f'{name} cmd_{case}')}) // ''",
            )
            or ""
        )

    async def switch_rule(self, name, enable):
        infos = await self.fetch_rules([name])
        info = infos.get(name)
        if info is None:
            return f"{name} not found"
        if info["TYPE"] == "DOIF":
            action = " enable" if enable else " disable"
            cmd = f"CommandSet(undef, {fhem.perlString(name + action)}) // ''"
        elif enable:
            cmd = (
                f"CommandDeleteAttr(undef, {fhem.perlString(name + ' disable')}) // ''"
            )
        else:
            cmd = f"CommandAttr(undef, {fhem.perlString(name + ' disable 1')}) // ''"
        self._own_changes.add(name)
        result = await fhem.sendCommandHash(self.hash, cmd)
        self.add_change(name, "enabled" if enable else "disabled")
        await self.save_data()
        self._index_time = 0
        return str(result or "")

    async def set_enable(self, hash, params):
        return await self.switch_rule(params.get("rule", ""), True)

    async def set_disable(self, hash, params):
        return await self.switch_rule(params.get("rule", ""), False)

    async def set_value_save(self, hash, params):
        return await self.with_reply(params, self.value_save)

    async def value_save(self, data):
        value = data.get("value") or {}
        old_name = data.get("old_name") or ""
        name = value.get("name") or values.reading_name(value.get("title"))
        if not values.NAME_RE.match(name):
            return "invalid name"
        if name != old_name and any(
            item["name"] == name for item in self.data["inputs"]
        ):
            return "name in use"
        value["name"] = name
        items = [
            v for v in self.data["values"] if v.get("name") not in (old_name, name)
        ]
        position = next(
            (
                i
                for i, v in enumerate(self.data["values"])
                if v.get("name") in (old_name, name)
            ),
            len(items),
        )
        items.insert(position, value)
        self.data["values"] = items
        if old_name and old_name != name:
            await self.delete_readings(old_name)
        self.add_change(self.hash["NAME"], "value", name)
        await self.save_data()
        await self.register_events()
        await self.compute_values()
        return dumps({"ok": True, "name": name})

    async def delete_readings(self, name):
        for reading in (name, name + "_s"):
            self._results.pop(reading, None)
            await fhem.CommandDeleteReading(self.hash, f"{self.hash['NAME']} {reading}")

    async def set_value_delete(self, hash, params):
        name = params.get("name", "")
        self.data["values"] = [v for v in self.data["values"] if v.get("name") != name]
        await self.delete_readings(name)
        self.add_change(self.hash["NAME"], "value_deleted", name)
        await self.save_data()
        await self.register_events()
        return ""

    async def set_input_save(self, hash, params):
        return await self.with_reply(params, self.input_save)

    async def input_save(self, data):
        item = data.get("input") or {}
        name = item.get("name") or values.reading_name(item.get("title"))
        if not values.NAME_RE.match(name):
            return "invalid name"
        if any(v.get("name") == name for v in self.data["values"]):
            return "name in use"
        item["name"] = name
        old = next((i for i in self.data["inputs"] if i["name"] == name), None)
        if old is not None and "value" in old and "value" not in item:
            item["value"] = old["value"]
        self.data["inputs"] = [i for i in self.data["inputs"] if i["name"] != name] + [
            item
        ]
        await self.save_data()
        await self.compute_values()
        return dumps({"ok": True, "name": name})

    async def set_input_delete(self, hash, params):
        name = params.get("name", "")
        self.data["inputs"] = [i for i in self.data["inputs"] if i["name"] != name]
        await self.delete_readings(name)
        await self.save_data()
        return ""

    async def set_input(self, hash, params):
        name = params.get("name", "")
        item = next((i for i in self.data["inputs"] if i["name"] == name), None)
        if item is None:
            return f"unknown input {name}"
        item["value"] = params.get("value", "")
        await self.save_data()
        await self.compute_values()
        return ""

    async def set_recompute(self, hash, params):
        self._results = {}
        await self.compute_values()
        return ""
