    async def get_now(self, hash, params):
        """what the rule would do now and why (not)"""
        try:
            data = decode(params.get("data"))
        except ValueError as exc:
            return dumps({"error": str(exc)})
        model = data.get("model") or {}
        if model.get("mode") != "fhem":
            return dumps({"cases": [], "case": None, "perl": True})
        name = model.get("name", "")
        ctx, current = await self.evaluation_context(model)
        state = {}
        if name:
            state = (await self.fetch_rules([name])).get(name, {})
        readings = state.get("readings", {})
        last_case = None
        match = re.match(r"cmd_(\d+)", str(readings.get("cmd", "")))
        if match:
            last_case = int(match.group(1)) - 1
        do_always = (model.get("attrs", {}) or {}).get("do") == "always"
        case = evaluate.which_case(ctx, model, None, True)
        cases = []
        for number, item in enumerate(model.get("cases", [])):
            cases.append(
                {
                    "leaves": (
                        evaluate.explain(ctx, item.get("cond"))
                        if item.get("cond")
                        else []
                    ),
                    "result": (
                        evaluate.eval_tree(ctx, item.get("cond"))
                        if item.get("cond")
                        else True
                    ),
                }
            )
        blocked = (
            isinstance(case, int)
            and case == last_case
            and not do_always
            and not (model.get("cases", [{}])[case].get("attrs", {}) or {}).get(
                "repeatsame"
            )
        )
        return dumps(
            {
                "case": case,
                "cases": cases,
                "last_case": last_case,
                "blocked": blocked,
                "disabled": (state.get("attrs", {}) or {}).get("disable", "0")
                not in ("", "0")
                or readings.get("mode") == "disabled",
                "wait_timer": readings.get("wait_timer", ""),
                "cmd_event": readings.get("cmd_event", ""),
                "values": {f"{d}:{r}": v[1] for (d, r), v in current.items()},
                "hints": self.hints(model),
            }
        )

    def hints(self, model):
        """pitfalls of a model: [{kind, case, fix}]"""
        result = []
        cases = model.get("cases", [])
        attrs = model.get("attrs", {}) or {}
        for number, case in enumerate(cases):
            cond = case.get("cond")
            if cond is None:
                continue
            triggers, checks, _, timers = parser.reads_and_writes(
                {"mode": "fhem", "cases": [{"cond": cond, "blocks": []}]}
            )
            if not triggers and not timers:
                result.append({"kind": "no_trigger", "case": number})
            text = parser.condition_text(cond)
            if (
                re.search(r"\[[^\]?]+\]\s*(==|eq)\s*\"?(on|off)\"?", text)
                and len(cases) == 1
            ):
                if attrs.get("do") != "always" and not any(
                    "repeatsame" in (c.get("attrs") or {}) for c in cases
                ):
                    result.append(
                        {"kind": "single_case", "case": number, "fix": "do_always"}
                    )
            for block in case.get("blocks", []):
                if str(block.get("wait") or "").strip() not in ("", "0") and (
                    attrs.get("do") == "always"
                ):
                    result.append({"kind": "wait_always", "case": number})
                    break
        self_writes = set()
        triggers, _, writes, _ = parser.reads_and_writes(model)
        for device in writes:
            if any(d == device for d, _ in triggers):
                self_writes.add(device)
        for device in sorted(self_writes):
            result.append({"kind": "self_trigger", "device": device})
        return result

