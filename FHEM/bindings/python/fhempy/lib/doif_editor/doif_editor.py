    # --- storage ------------------------------------------------------------

    def data_path(self):
        return os.path.join(
            os.getcwd(), ".fhempy", "doif_editor", f"{self.hash['NAME']}.json"
        )

    def load(self):
        try:
            with open(self.data_path(), encoding="utf-8") as file:
                loaded = json.load(file)
            for key in self.data:
                if isinstance(loaded.get(key), type(self.data[key])):
                    self.data[key] = loaded[key]
        except FileNotFoundError:
            pass
        except (OSError, ValueError):
            self.logger.exception("Failed to read the stored values and versions")

    def _write(self, text):
        path = self.data_path()
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as file:
            file.write(text)
        os.replace(tmp, path)

    async def save_data(self):
        text = json.dumps(self.data, ensure_ascii=False, indent=1, default=list)
        await utils.run_blocking(functools.partial(self._write, text))

    def add_change(self, rule, action, detail=""):
        self.data["changes"].append(
            {"ts": time.time(), "rule": rule, "action": action, "detail": detail}
        )
        del self.data["changes"][:-MAX_CHANGES]

    def add_version(self, rule, rule_type, definition, attrs, note=""):
        versions = self.data["versions"].setdefault(rule, [])
        if (
            versions
            and versions[-1]["def"] == definition
            and versions[-1].get("attrs") == attrs
        ):
            return False
        versions.append(
            {
                "ts": time.time(),
                "type": rule_type,
                "def": definition,
                "attrs": attrs,
                "note": note,
            }
        )
        del versions[:-MAX_VERSIONS]
        return True

