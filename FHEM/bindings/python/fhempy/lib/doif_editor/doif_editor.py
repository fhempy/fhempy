def decode(token):
    """JSON token of the frontend: base64url without padding, FHEM would take
    a "=" as named argument"""
    text = str(token or "")
    if not re.fullmatch(r"[A-Za-z0-9_-]*", text):
        raise ValueError("invalid data")
    try:
        raw = base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))
        return json.loads(raw.decode("utf-8"))
    except (binascii.Error, UnicodeDecodeError, ValueError) as exc:
        raise ValueError(f"invalid data: {exc}") from exc


def encode(data):
    return (
        base64.urlsafe_b64encode(json.dumps(data).encode("utf-8")).decode().rstrip("=")
    )


def dumps(data):
    # every byte goes through FHEM
    return json.dumps(data, ensure_ascii=False, separators=(",", ":"), default=list)


def parse_sets(text):
    """getAllSets text -> [{cmd, options}]"""
    result = []
    for word in str(text or "").split():
        cmd, _, options = word.partition(":")
        if not cmd or cmd == "?":
            continue
        result.append({"cmd": cmd, "options": options})
    return result


