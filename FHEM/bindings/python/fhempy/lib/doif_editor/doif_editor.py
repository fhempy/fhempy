    async def apply_rule(self, name, rule_type, definition, attrs, managed):
        """checks the definition with a temporary device, then defines or
        modifies the rule and sets/deletes the attributes"""
        if not RULE_NAME_RE.match(name or ""):
            return "invalid name"
        if rule_type not in index.RULE_TYPES:
            return "invalid type"
        attr_cmds = []
        for attr in sorted(managed | set(attrs)):
            value = attrs.get(attr)
            if value is None or value == "":
                attr_cmds.append(
                    f"CommandDeleteAttr(undef, {fhem.perlString(name + ' ' + attr)})"
                    f" if (defined(AttrVal({fhem.perlString(name)},"
                    f" {fhem.perlString(attr)}, undef)));"
                )
            else:
                attr_cmds.append(
                    f"if (AttrVal({fhem.perlString(name)}, {fhem.perlString(attr)},"
                    f" '\\x00') ne {fhem.perlString(str(value))}) {{"
                    " my $e = CommandAttr(undef, "
                    + fhem.perlString(f"{name} {attr} {value}")
                    + "); push(@err, $e) if ($e) }"
                )
        tmp = name + TEMP_SUFFIX
        cmd = (
            "(sub { my @err; my $n = " + fhem.perlString(name) + ";"
            " my $tp = " + fhem.perlString(rule_type) + ";"
            " my $def = " + fhem.perlString(definition) + ";"
            " my $tmp = " + fhem.perlString(tmp) + ";"
            " return 'type' if (defined($defs{$n}) && $defs{$n}{TYPE} ne $tp);"
            ' my $e = CommandDefine(undef, "-temporary $tmp $tp $def");'
            " CommandDelete(undef, $tmp) if (defined($defs{$tmp}));"
            " return $e if ($e);"
            " if (defined($defs{$n})) {"
            "  if (($defs{$n}{DEF} // '') ne $def) {"
            '  $e = CommandModify(undef, "$n $def");'
            "  return $e if ($e) } }"
            ' else { $e = CommandDefine(undef, "$n $tp $def"); return $e if ($e) }'
            + " ".join(attr_cmds)
            + ' return @err ? join("\\n", @err) : "ok"; })->()'
        )
        self._own_changes.add(name)
        result = await fhem.sendCommandHash(self.hash, cmd)
        self._index_time = 0
        if result == "ok":
            return ""
        # None: Perl error, details in the FHEM log
        return str(result or "FHEM couldn't save the rule, see the FHEM log")

