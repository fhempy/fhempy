"""Catalog of discoverable devices and matching of found network devices.

The catalog (discovery.json) is generated by manifest2modules.py from the
"discovery" section of every module's manifest.json. Each module has one or
more rules. A rule says how its devices are recognized (mdns, ssdp, ble or the
module's own search() in discovery.py) and how a found device is created.

Values like "{txt.fn}" are templates, filled with the data of the found device:
- mdns: name, host, ip, port, type, txt.<key>
- ssdp: udn, friendly_name, manufacturer, model_name, device_type, ip
- ble: address, name, rssi, homekit_id (unpaired HomeKit devices)
- search(): the keys the module's search() passes to ctx.found()
"""

import fnmatch
import json
import os
import re

from .. import utils

CATALOG_FILE = os.path.join(os.path.dirname(__file__), "discovery.json")

# Bluetooth devices of the neighbours shouldn't show up
DEFAULT_MIN_RSSI = -80

_TEMPLATE = re.compile(r"\{([A-Za-z0-9_.-]+)\}")


def load(path=CATALOG_FILE):
    with open(path, encoding="utf-8") as catalog_file:
        return json.load(catalog_file)


def render(template, values):
    """Fills {key} and {txt.key} placeholders, unknown keys become ''."""
    if not isinstance(template, str):
        return template

    def value(match):
        found = values
        for part in match.group(1).split("."):
            if not isinstance(found, dict) or part not in found:
                return ""
            found = found[part]
        return "" if found is None else str(found)

    return _TEMPLATE.sub(value, template).strip()


def device_name(text, fallback):
    """FHEM device name from a title, e.g. 'Living Room TV' -> Living_Room_TV"""
    name = utils.gen_fhemdev_name(str(text or ""))
    name = re.sub(r"[^A-Za-z0-9._]", "", name).strip("._")
    return name or fallback


def rules(catalog, source):
    """(entry, rule) of all rules with the given source (mdns, ssdp, ble, search)"""
    for entry in catalog:
        for rule in entry["rules"]:
            if rule.get(source):
                yield entry, rule


def mdns_types(catalog):
    types = set()
    for _, rule in rules(catalog, "mdns"):
        for matcher in rule["mdns"]:
            types.add(matcher["type"])
    return sorted(types)


def ssdp_types(catalog):
    types = set()
    for _, rule in rules(catalog, "ssdp"):
        for matcher in rule["ssdp"]:
            types.add(matcher["device_type"])
    return sorted(types)


def _glob(value, pattern):
    return fnmatch.fnmatchcase(str(value or ""), str(pattern))


def _txt_matches(txt, filters):
    return all(_glob(txt.get(key), pattern) for key, pattern in filters.items())


def match_mdns(catalog, service_type, values):
    """values: name, host, ip, port, type and txt (dict of str)"""
    for entry, rule in rules(catalog, "mdns"):
        for matcher in rule["mdns"]:
            if matcher["type"] != service_type:
                continue
            if _txt_matches(values.get("txt", {}), matcher.get("txt", {})):
                yield entry, rule
                break


def match_ssdp(catalog, values):
    """values: device_type, manufacturer, model_name, friendly_name, udn, ip"""
    for entry, rule in rules(catalog, "ssdp"):
        for matcher in rule["ssdp"]:
            if matcher["device_type"] != values.get("device_type"):
                continue
            if all(
                _glob(values.get(key), pattern)
                for key, pattern in matcher.items()
                if key != "device_type"
            ):
                yield entry, rule
                break


def _ble_matcher_matches(matcher, name, manufacturer_data, uuids):
    if "name" in matcher and name != matcher["name"]:
        return False
    if "name_prefix" in matcher and not (name or "").startswith(
        tuple(_as_list(matcher["name_prefix"]))
    ):
        return False
    if "manufacturer_id" in matcher and matcher["manufacturer_id"] not in (
        manufacturer_data
    ):
        return False
    if "manufacturer_data_prefix" in matcher and not bytes(
        manufacturer_data.get(matcher.get("manufacturer_id"), b"")
    ).startswith(bytes.fromhex(matcher["manufacturer_data_prefix"])):
        return False
    if "service_uuid" in matcher and matcher["service_uuid"].lower() not in uuids:
        return False
    return True


def _as_list(value):
    return value if isinstance(value, list) else [value]


APPLE_MANUFACTURER_ID = 76
HOMEKIT_ADVERTISEMENT = 0x06


def homekit_id(manufacturer_data):
    """HomeKit device id (like txt.id of mDNS) of an unpaired HAP-BLE device,
    '' otherwise. Apple data: type 0x06, length, status flags, device id."""
    data = bytes(manufacturer_data.get(APPLE_MANUFACTURER_ID, b""))
    if len(data) < 9 or data[0] != HOMEKIT_ADVERTISEMENT:
        return ""
    # status flag bit 0: not paired yet, mDNS rule filters sf=1 the same way
    if not data[2] & 0x01:
        return ""
    return ":".join(f"{byte:02X}" for byte in data[3:9])


def match_ble(catalog, name, manufacturer_data, uuids, rssi):
    """manufacturer_data: {manufacturer id: bytes},
    uuids: lowercase service UUIDs and service data UUIDs of the advertisement"""
    for entry, rule in rules(catalog, "ble"):
        if rssi is not None and rssi < rule.get("min_rssi", DEFAULT_MIN_RSSI):
            continue
        for matcher in rule["ble"]:
            if _ble_matcher_matches(matcher, name, manufacturer_data, uuids):
                yield entry, rule
                break


def candidate(entry, rule, values, source):
    """A found device as shown in the popup, None if it can't be identified."""
    module = entry["module"]
    unique = render(rule.get("unique", ""), values)
    if rule.get("single"):
        unique = module
    if not unique:
        return None
    title = render(rule.get("title", ""), values) or entry["title"]
    name_template = rule.get("name")
    name = device_name(
        render(name_template, values) if name_template else title, entry["name"]
    )
    found = {
        "id": f"{module}:{unique}",
        "module": module,
        "unique": unique,
        "title": title,
        "model": render(rule.get("model", ""), values),
        "kind": entry["title"],
        "name": name,
        "ip": values.get("ip", ""),
        "source": source,
        "action": rule.get("action", "define"),
        "define": [render(arg, values) for arg in rule.get("define", [])],
        "params": rule.get("params", []),
        "hint": rule.get("hint", ""),
        # searched in the DEF of existing devices of the module
        "exists": render(rule.get("exists") or rule.get("unique", ""), values)
        or unique,
    }
    for key in ("logo", "icon"):
        if entry.get(key):
            found[key] = entry[key]
    if found["action"] == "set":
        found["set"] = {
            **rule["set"],
            "args": [render(arg, values) for arg in rule["set"].get("args", [])],
        }
    if found["action"] == "installer":
        found["prefill"] = {
            index: render(value, values)
            for index, value in rule.get("prefill", {}).items()
        }
    return found
